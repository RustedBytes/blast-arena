//! Generates the table of browser-client files (`static/`) that release
//! builds compile into the server binary (see `src/embedded.rs`). Debug
//! builds don't use it: they serve `static/` from disk, so client edits show
//! up on reload without rebuilding.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

fn main() {
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR"));
    let root = manifest.join("static");
    // A directory here makes Cargo rescan everything inside it.
    println!("cargo:rerun-if-changed=static");
    println!("cargo:rerun-if-changed=client");
    println!("cargo:rerun-if-changed=build.rs");
    check_client(manifest);

    let mut files = Vec::new();
    collect(&root, &mut files);
    // Sorted by URL path, so the server can binary-search the table.
    let mut entries: Vec<(String, PathBuf)> = files
        .into_iter()
        .map(|p| {
            let rel = p.strip_prefix(&root).expect("inside static/");
            let url = rel.components().map(|c| c.as_os_str().to_string_lossy()).collect::<Vec<_>>().join("/");
            (url, p)
        })
        .collect();
    entries.sort();

    let mut out = String::from("/// (URL path, contents, quoted `ETag`), sorted by path. Generated by `build.rs`.\n");
    out.push_str("pub static FILES: &[(&str, &[u8], &str)] = &[\n");
    for (url, path) in &entries {
        let bytes = fs::read(path).expect("readable client file");
        let abs = path.canonicalize().expect("canonical path");
        writeln!(out, "    ({url:?}, include_bytes!({:?}), \"\\\"{:016x}\\\"\"),", abs.display().to_string(), fnv1a(&bytes)).unwrap();
    }
    out.push_str("];\n");
    let dest = Path::new(&env::var("OUT_DIR").expect("OUT_DIR set by cargo")).join("embedded_static.rs");
    fs::write(dest, out).expect("write the generated table");
}

/// The browser client is written in TypeScript and CSS (`client/`) and built
/// by `deno task build` into one minified script per page in `static/js/` plus
/// `static/style.css`, which is what gets embedded. Stops the build when it
/// hasn't been built, and warns when a client source file is newer than the
/// output.
fn check_client(manifest: &Path) {
    let out = manifest.join("static");
    let bundles = ["js/main.js", "js/dashboard.js", "js/tilelab.js", "style.css"].map(|b| out.join(b));
    assert!(
        bundles.iter().all(|b| b.is_file()),
        "the browser client isn't built: run `deno install && deno task build` first (builds client/ into static/js/ and static/style.css)"
    );
    let modified = |p: &Path| fs::metadata(p).and_then(|m| m.modified()).ok();
    let Some(built) = bundles.iter().filter_map(|b| modified(b)).min() else { return };
    let mut sources = Vec::new();
    collect(&manifest.join("client"), &mut sources);
    if let Some(src) = sources.iter().find(|s| modified(s).is_some_and(|t| t > built)) {
        println!("cargo:warning=the built client in static/ is out of date with client/ ({}): run `deno task build`", src.display());
    }
}

/// Every regular file under `dir`, skipping hidden ones (`.DS_Store` and such).
fn collect(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(read) = fs::read_dir(dir) else { return };
    for entry in read.flatten() {
        let path = entry.path();
        if entry.file_name().to_string_lossy().starts_with('.') {
            continue;
        }
        if path.is_dir() {
            collect(&path, out);
        } else if path.is_file() {
            out.push(path);
        }
    }
}

/// 64-bit FNV-1a: a stable content hash for `ETag`s.
fn fnv1a(bytes: &[u8]) -> u64 {
    bytes.iter().fold(0xcbf2_9ce4_8422_2325, |h, &b| (h ^ u64::from(b)).wrapping_mul(0x0100_0000_01b3))
}
